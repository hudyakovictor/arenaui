export const TOTAL = categories.reduce((s, c) => s + c.items.length, 0);

export function scoreOf(items: Factor[]) {
  const pts = items.reduce((s, i) => s + i.status, 0);
  return Math.round((pts / (items.length * 2)) * 100);
}

export function currentScore() {
  return scoreOf(categories.flatMap((c) => c.items));
}

export function targetScore() {
  const all = categories.flatMap((c) => c.items);
  const pts = all.reduce((s, i) => s + (i.deferred ? 0 : 2), 0);
  return Math.round((pts / (all.length * 2)) * 100);
}

export function counts(items: Factor[]) {
  return {
    ok: items.filter((i) => i.status === 2).length,
    partial: items.filter((i) => i.status === 1).length,
    missing: items.filter((i) => i.status === 0).length,
  };
}
