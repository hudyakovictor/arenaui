export const factors: Factor[] = raw.map(([cat, p, t], i) => ({
  id: `F${String(i + 1).padStart(3, '0')}`,
  cat,
  p,
  t,
}));

export const weightOf = (p: Priority) => (p === 0 ? 3 : p === 1 ? 2 : 1);
export const totalWeight = factors.reduce((s, f) => s + weightOf(f.p), 0);
export const START_SCORE = 25;
export const TARGET_SCORE = 99;

export function scoreFor(doneIds: Set<string>): number {
  const w = factors.reduce((s, f) => (doneIds.has(f.id) ? s + weightOf(f.p) : s), 0);
  return Math.round((START_SCORE + ((TARGET_SCORE - START_SCORE) * w) / totalWeight) * 10) / 10;
}
